def credits(sid):
    e = json.load(open(f"shorts/{sid}/edit.json"))
    names = []
    for s in e["sources"].values():
        if s["seconds"]:
            n = s["creator"].split(" (")[0]
            if n not in names: names.append(n)
    m = e["music"]["file"].split("/")[-1][:-4]
    return names, MUSIC[m]

