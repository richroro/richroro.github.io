def spec(sid):
    t, summary, tags, pin = TEXT[sid]
    e = json.load(open(f"{ROOT}/shorts/{sid}/edit.json"))
    photos = [f"사진: {s['credit']}" for s in e["sources"].values()]
    return {"title": t, "summary": summary, "fiction": True,
            "sources": ["그림·대본·목소리 직접 제작(등장인물·채팅방은 실제와 관계없음)"] + photos,
            "tags": COMMON + tags, "pinned": pin}

if __name__ == "__main__":
    os.makedirs(f"{ROOT}/upload/specs", exist_ok=True)
    for sid in sys.argv[1:] or TEXT:
        json.dump(spec(sid), open(f"{ROOT}/upload/specs/{sid}.json", "w"), ensure_ascii=False, indent=2)
        print(sid)
